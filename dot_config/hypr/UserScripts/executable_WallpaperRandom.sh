#!/bin/bash
# /* ---- 💫 https://github.com/JaKooLit 💫 ---- */  ##
# Script for Random Wallpaper ( CTRL ALT W)

wallDIR="$HOME/Pictures/wallpapers"
SCRIPTSDIR="$HOME/.config/hypr/scripts"

# shellcheck source=/home/vango/.config/hypr/scripts/WallpaperBackend.sh
source "$SCRIPTSDIR/WallpaperBackend.sh"

focused_monitor=$(hyprctl monitors -j | jq -r '.[] | select(.focused) | .name')

PICS=($(find -L ${wallDIR} -type f \( -name "*.jpg" -o -name "*.jpeg" -o -name "*.png" -o -name "*.pnm" -o -name "*.tga" -o -name "*.tiff" -o -name "*.webp" -o -name "*.bmp" -o -name "*.farbfeld" -o -name "*.gif" \)))
RANDOMPICS=${PICS[ $RANDOM % ${#PICS[@]} ]}


# Transition config
FPS=30
TYPE="random"
DURATION=1
BEZIER=".43,1.19,1,.4"
SWWW_PARAMS="--transition-fps $FPS --transition-type $TYPE --transition-duration $DURATION --transition-bezier $BEZIER"


wallpaper_start_daemon || exit 1
wallpaper_img -o "$focused_monitor" "${RANDOMPICS}" $SWWW_PARAMS || exit 1
"$SCRIPTSDIR/WallustSwww.sh" "${RANDOMPICS}" || exit 1
sleep 2
"$SCRIPTSDIR/Refresh.sh"
